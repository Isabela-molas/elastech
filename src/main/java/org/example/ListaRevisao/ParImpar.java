package org.example.ListaRevisao;

public class ParImpar {
    static void main() {
        for (int i = 1; i <= 15; i++){
            if (i % 2 == 0){
                System.out.println(i + " é Par");
            }else{
                System.out.println(i + " é Ímpar");
            }
        }
    }
}
/*
    0-> onde começa
    int i-> contador
    i<=5 -> até quando
    i++ -> como avança
 */